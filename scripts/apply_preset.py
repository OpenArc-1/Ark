PRESETS = {
    "defconfig":  DEFCONFIG,
    "tinyconfig": TINYCONFIG,
    "allyes":     ALLYES,
    "allno":      ALLNO,
}

def main():
    if len(sys.argv) != 3:
        print("usage: apply_preset.py <preset> <output>", file=sys.stderr)
        print("presets: " + " | ".join(PRESETS), file=sys.stderr)
        return 2
    preset, outpath = sys.argv[1], sys.argv[2]
    if preset not in PRESETS:
        print(f"apply_preset.py: unknown preset '{preset}'", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(outpath) or ".", exist_ok=True)
    with open(outpath, "w", encoding="utf-8") as f:
        f.write(PRESETS[preset])
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
